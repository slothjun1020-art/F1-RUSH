export const TRACKS = TRACK_DEFS.map((d) => ({ ...d, lapLength: d.km * KM, width: WIDTH }));

const cache = new Map();

export function getTrack(id) {
  if (!cache.has(id)) {
    const def = TRACKS.find((t) => t.id === id);
    if (!def) return null;
    cache.set(id, buildTrack(def));
  }
  return cache.get(id);
}

export function trackList() {
  return TRACKS.map(({ id, name, en, country, km, color }) => ({ id, name, en, country, km, color }));
}
